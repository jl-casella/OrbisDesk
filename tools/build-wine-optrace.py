"""Proven Unix ABI wrappers and timed-yield optimization; no PE ABI changes."""
import hashlib,json,pathlib,re,subprocess
from wine_delay_yield import patch
from wine_read_trace import patch as patch_read
from wine_thread_alert_pending import patch as patch_alert_pending
ROOT=pathlib.Path(__file__).resolve().parents[1];UNIX=ROOT/'.deps/wine/ps4-unix'
work=ROOT/'build/wine-optrace'
if work.is_symlink():raise SystemExit('Operation trace output must be private, not a symlink to another checkout')
work.mkdir(exist_ok=True)
sha=lambda p:hashlib.sha256(pathlib.Path(p).read_bytes()).hexdigest()
base=json.loads((ROOT/'build/wine-boot/report.json').read_text());sync=next(x for x in base['results'] if x['unit']=='sync')
command=sync['command'];original=pathlib.Path(command[command.index('-o')+2]);assert sha(original)==sync['source_sha256']
if not original.is_relative_to(ROOT):
    # Reports copied into a worktree retain their producer's absolute source
    # argv. Bind that input to a declared read-only dependency alias; never edit
    # the producer's report or accept arbitrary paths as local build inputs.
    for relative in ('.deps/wine/ps4-overlay','.deps/wine/source'):
        alias=ROOT/relative
        if original.is_relative_to(alias.resolve()):
            original=alias/original.relative_to(alias.resolve())
            break
    else:raise SystemExit('Operation trace input is outside declared Wine sources')
file_source=ROOT/'build/wow64-world-ps4/file.c';world=json.loads((ROOT/'build/wow64-world-ps4/report.json').read_text())
assert sha(file_source)==world['sources']['file']
file_object=ROOT/'build/wow64-world-ps4/file.o'
proven_file=next(v for v in world['replaces'].values() if v['object']=='build/wow64-world-ps4/file.o')
if sha(file_object)!=proven_file['sha256']:raise SystemExit('World file object differs from its proven manifest')
win32u=json.loads((ROOT/'build/win32u-ps4/report.json').read_text())
message_name=next(name for name in win32u['sources'] if name.endswith('/message.c'))
message_source=ROOT/message_name
if sha(message_source)!=win32u['sources'][message_name]:raise SystemExit('Win32u message source differs from its proven manifest')
texts={'sync':original.read_text(),'file':file_source.read_text(),'message':message_source.read_text()}
names={'NtReadFile':('file','PW_OP_READ','handle,event,apc,apc_user,io,buffer,length,offset,key','length'),
 'NtWaitForSingleObject':('sync','PW_OP_WAIT_ONE','handle,alertable,timeout','0'),
 'NtWaitForMultipleObjects':('sync','PW_OP_WAIT_MANY','count,handles,type,alertable,timeout','0'),
 'NtDelayExecution':('sync','PW_OP_DELAY','alertable,timeout','0'),
 'NtYieldExecution':('sync','PW_OP_YIELD','','0'),
 'NtQueryPerformanceCounter':('sync','PW_OP_QPC','counter,frequency','0'),
 'NtWaitForAlertByThreadId':('sync','PW_OP_WAIT_ALERT','address,timeout','0'),
 'NtAlertThreadByThreadId':('sync','PW_OP_ALERT','tid','0'),
 'NtSetEvent':('sync','PW_OP_SET_EVENT','handle,prev_state','0'),
 'NtResetEvent':('sync','PW_OP_RESET_EVENT','handle,prev_state','0'),
 'NtUserPeekMessage':('message','PW_OP_PEEK','msg_out,hwnd,first,last,flags','0'),
 'NtUserMsgWaitForMultipleObjectsEx':('message','PW_OP_MSG_WAIT','count,handles,timeout,mask,flags','0')}
text='''/* Generated by tools/build-wine-optrace.py, from pinned Wine signatures. */
#include "config.h"
#include "ntstatus.h"
#define WIN32_NO_STATUS
#include "windef.h"
#include "winternl.h"
#include "winuser.h"
#include "pw_optrace.inc.c"
'''
for name,(unit,kind,args,requested) in names.items():
 matches=list(re.finditer(r'(?:NTSTATUS|BOOL|DWORD) WINAPI '+name+r'\s*\([^{};]*?\)\s*\{',texts[unit]));assert len(matches)==1,name
 signature=matches[0].group().rstrip().removesuffix('{').strip()
 text+='extern '+signature.replace(name,'__real_'+name)+';\n'
 text+=signature.replace(name,'__wrap_'+name)+'''\n{
    struct pw_opstamp stamp=pw_optrace_begin();
    '''+signature.split()[0]+''' result=__real_'''+name+'('+args+''');
    pw_optrace_end(stamp,'''+kind+',result,'+requested+''');
    return result;
}
'''
objects={}
file_command=next(x for x in base['results'] if x['unit']=='file')['command']
for unit,content in (('optrace',text),('sync',patch(patch_alert_pending(texts['sync']))),('file',patch_read(texts['file']))):
 source=work/(unit+'.c');source.write_text(content);obj=work/(unit+'.o')
 selected_command=command if unit!='file' else file_command
 selected_original=selected_command[selected_command.index('-o')+2]
 recipe=[str(source) if x==selected_original else str(obj) if i==selected_command.index('-o')+1 else x for i,x in enumerate(selected_command)]
 recipe[1:1]=['-I'+str(ROOT/'platform/ps4'),'-I'+str(original.parent)]
 if unit=='file':recipe[1:1]=['-I'+str(ROOT/'build/wow64-world-ps4/include')]
 with (work/(unit+'.log')).open('w') as log:result=subprocess.run(recipe,cwd=UNIX,stdout=log,stderr=subprocess.STDOUT)
 if result.returncode:raise SystemExit('Cannot compile '+unit+'; see '+str(work/(unit+'.log')))
 objects[unit]={'path':str(obj.relative_to(ROOT)),'sha256':sha(obj),'source_sha256':sha(source)}
sources=('platform/ps4/pw_optrace.h','platform/ps4/pw_optrace.inc.c','tools/wine_delay_yield.py','tools/wine_read_trace.py','tools/build-wine-optrace.py',
         'tools/wine_thread_alert_pending.py','platform/ps4/pw_thread_alert_pending.inc.c','platform/ps4/pw_wine_thread_alert.inc.c')
report={'objects':objects,'wraps':list(names),'replaces':'build/wine-boot/sync.o',
 'original_sync_object_sha256':sha(ROOT/'build/wine-boot/sync.o'),
 'replaces_file':'build/wow64-world-ps4/file.o','original_file_object_sha256':sha(ROOT/'build/wow64-world-ps4/file.o'),
 'inputs':{str(p.relative_to(ROOT)):sha(p) for p in (original,file_source,message_source)},
 'source_hashes':{name:sha(ROOT/name) for name in sources}}
(work/'report.json').write_text(json.dumps(report,indent=2)+'\n');print(json.dumps({'compiled':list(objects),'wraps':list(names)}))
